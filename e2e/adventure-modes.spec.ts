import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 1920, height: 1080 }, { width: 1366, height: 768 }, { width: 390, height: 844 }]) {
  test(`aventuras preparadas y laboratorio sin IA a ${viewport.width}`, async ({ page }) => {
    await page.setViewportSize(viewport)
    await page.addInitScript(() => {
      localStorage.setItem('cronicas-nexo-howto-visto', '1')
      localStorage.setItem('cronicas-nexo-preferences', JSON.stringify({ state: { selectedDeckId: 'furia-caldera', muted: true, reducedMotion: true, graphicsQuality: 'low' }, version: 7 }))
    })
    await page.goto('/adventures')
    await expect(page.getByRole('heading', { name: 'La Cámara de las Crónicas' })).toBeVisible()
    await page.getByRole('button', { name: 'Preparar capítulo', exact: true }).first().click()
    const active = page.getByRole('region', { name: 'Aventura en curso' })
    await expect(active).toContainText('La llamada')
    await expect(active.getByRole('button', { name: 'Entrar en batalla' })).toBeVisible()
    await page.screenshot({ path: `tools/captures/adventures/campana-${viewport.width}.png` })
    await active.getByRole('button', { name: 'Abandonar aventura' }).click()
    await page.getByRole('tab', { name: 'Guardianes del Nexo' }).click()
    await page.getByRole('combobox', { name: 'Guardián', exact: true }).selectOption('hambre-vacio')
    await page.getByRole('button', { name: 'Preparar desafío' }).click()
    await expect(active).toContainText('El Hambre entre Mundos')
    await expect(active).toContainText('Segunda fase')
    await active.getByRole('button', { name: 'Abandonar aventura' }).click()
    await page.getByRole('tab', { name: 'Duelo al mejor de tres' }).click()
    await page.getByRole('button', { name: 'Preparar serie' }).click()
    await expect(active).toContainText('Combate 1 · 0 — 0')
    await active.getByRole('button', { name: 'Abandonar aventura' }).click()
    await page.goto('/laboratory')
    await expect(page.getByRole('heading', { name: 'Laboratorio del Nexo' })).toBeVisible()
    await expect(page.getByRole('group', { name: 'Casillas de prueba' }).getByRole('button')).toHaveCount(64)
    await page.getByLabel('Buscar carta', { exact: true }).fill('Sabueso de Brasa')
    await page.getByRole('button', { name: 'Añadir a la mano', exact: true }).click()
    await page.getByRole('button', { name: /^Sabueso de Brasa\./ }).last().click()
    await page.getByRole('button', { name: 'Casilla 1,8, vacía', exact: true }).click()
    await expect(page.getByRole('button', { name: /^Casilla 1,8, Sabueso de Brasa/ })).toBeVisible()
    await page.getByRole('button', { name: /^Casilla 1,8, Sabueso de Brasa/ }).click()
    await page.getByRole('button', { name: 'Casilla 2,8, vacía', exact: true }).click()
    await expect(page.getByRole('button', { name: /^Casilla 2,8, Sabueso de Brasa/ })).toBeVisible()
    await page.getByRole('button', { name: 'Terminar turno y controlar al otro bando' }).click()
    await expect(page.getByRole('region', { name: 'Controles de entrenamiento' })).toContainText('Turno 2 · Controlas al bando de pruebas')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('group', { name: 'Casillas de prueba' }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: `tools/captures/adventures/laboratorio-${viewport.width}.png` })
    expect(await page.evaluate(() => localStorage.getItem('cronicas-nexo-match'))).toBeNull()
  })
}

